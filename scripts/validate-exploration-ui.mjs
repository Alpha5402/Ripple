await graph.getByRole('button',{name:'复位',exact:true}).click();
await graph.locator('.graph-node').first().focus(); assert(await graph.locator('.graph-muted').count()>0);
await page.waitForTimeout(350); await page.screenshot({path:'reports/local/product-flow/neighborhood-focus.png'});
console.log('before-evidence',await page.evaluate(async()=> (await window.ripple.command({type:'state'})).result.current.reading));
const camera=await graph.locator('svg.local-graph > g').getAttribute('transform');
await graph.locator('.graph-edge').first().press('Enter'); await page.getByRole('button',{name:'定位原文',exact:true}).first().waitFor();
const relation=await page.locator('.relation-between').textContent();
await page.getByRole('button',{name:'定位原文',exact:true}).first().click(); await page.getByRole('textbox',{name:'关系来源原文'}).waitFor();
const selection=await page.getByRole('textbox',{name:'关系来源原文'}).evaluate(el=>({start:el.selectionStart,end:el.selectionEnd})); assert(selection.end>selection.start);
await page.getByRole('button',{name:'← 返回关系与图谱',exact:true}).click();
