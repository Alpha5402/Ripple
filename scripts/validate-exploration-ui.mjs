console.log('returned-scroll',await page.locator('.reading-body').evaluate(el=>({top:el.scrollTop,height:el.scrollHeight,client:el.clientHeight})));
assert(await page.locator('.reading-body').evaluate(el=>el.scrollTop)>0, 'Reading position was not restored');
await page.getByRole('button',{name:'全局',exact:true}).click();
await graph.locator('.graph-edge').first().press('Enter');
await page.waitForTimeout(350); await page.screenshot({path:'reports/local/product-flow/evidence-return.png'});
console.log(JSON.stringify({imported:11,excludedUnreadable:1,labels:{small,large},neighborhood:true,sourceSelection:selection,returnedRelation:relation}));
