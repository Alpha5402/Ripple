assert.equal(await graph.locator('svg.local-graph > g').getAttribute('transform'),camera);
const restored=await page.evaluate(async()=> (await window.ripple.command({type:'state'})).result.current.reading.documentId);
assert(restored);console.log('after-return',await page.evaluate(async()=> (await window.ripple.command({type:'state'})).result.current.reading));
